import logging
_logger = logging.getLogger(__name__)
from odoo import models, fields, api, _

class HrContract(models.Model):
    _inherit = 'hr.contract'

    add_standart = fields.Float(
        string="Hours to pay at extra rate",
        help="This many hours of Attendance get paid at the add_extra rate"
    )
    
    add_extra = fields.Float(
        string="Extra hour rate",
        help="Rate to apply to the first add_standart hours of Attendance"
    )
    
    paga_ne_banke = fields.Float(string="Paga ne Banke")



class HrPayslip(models.Model):
    _inherit = 'hr.payslip'

    
    attendance_ids = fields.Many2many(
        'hr.attendance',
        string='Attendances',
        compute='_compute_attendance_ids',
        store=False,
    )

    
    @api.depends('employee_id', 'date_from', 'date_to')
    def _compute_attendance_ids(self):
        Attendance = self.env['hr.attendance']
        for slip in self:
            if slip.employee_id and slip.date_from and slip.date_to:
                attends = Attendance.search([
                    ('employee_id', '=', slip.employee_id.id),
                    ('check_in', '>=', slip.date_from),
                    ('check_out', '<=', slip.date_to),
                ], order='check_in')
                slip.attendance_ids = attends
            else:
                slip.attendance_ids = False


    
    paga_ne_banke = fields.Float(string="Paga ne Banke", related="contract_id.paga_ne_banke")
    
    def _get_worked_day_lines(self, *args, **kwargs):
        lines = super()._get_worked_day_lines(*args, **kwargs)
    
        if self.contract_id.wage_type == 'monthly':
            return lines  # Skip logic for monthly contracts
    
        extras = []
    
        for l in lines:
            wtype = l.get('work_entry_type_id') and self.env['hr.work.entry.type'].browse(l['work_entry_type_id'])
            if not wtype or wtype.code != 'WORK100':
                continue  # Skip if work entry type is not 'WORK100'
    
            total_hours = l['number_of_hours'] or 0.0
            contract = self.contract_id
            threshold = contract.add_standart or 0.0
            
            if threshold <= 0:
                continue  

            extra_hours = total_hours - threshold
            
            if threshold > total_hours:
                continue
            
            l['number_of_hours'] = threshold
            l['number_of_days'] = threshold / 8.0
            
            # Create extra line if needed
            if extra_hours > 0:
                extra_line = l.copy()
    
                # Ensure all required fields are set for the extra line
                extra_line.update({
                    'name': _('Totali'),
                    'custom_bool': True,
                    'number_of_hours': extra_hours,
                    'number_of_days': extra_hours / 8.0,  # Assume 8-hour workday
                })
    
                extras.append(extra_line)
    
        lines.extend(extras)
        return lines


    def _get_rule_name(self, localdict, rule, employee_lang):
        if localdict['result_name']:
            rule_name = localdict['result_name']
        elif rule.code in ['BASIC', 'GROSS', 'NET', 'DEDUCTION',
                           'REIMBURSEMENT']:  # Generated by default_get (no xmlid)
            if rule.code == 'BASIC':  # Note: Crappy way to code this, but _(foo) is forbidden. Make a method in master to be overridden, using the structure code
                if rule.name == "Double Holiday Pay":
                    rule_name = _("Double Holiday Pay")
                if rule.struct_id.name == "CP200: Employees 13th Month":
                    rule_name = _("Prorated end-of-year bonus")
                else:
                    rule_name = _('Totali')
            elif rule.code == "GROSS":
                rule_name = _('Paga Bruto')
            elif rule.code == "DEDUCTION":
                rule_name = _('Deduction')
            elif rule.code == "REIMBURSEMENT":
                rule_name = _('Reimbursement')
            elif rule.code == 'NET':
                rule_name = _('Diferenca')
        else:
            rule_name = rule.with_context(lang=employee_lang).name
        return rule_name


class HrPayslipWorkedDays(models.Model):
    _inherit = 'hr.payslip.worked_days'

    custom_bool = fields.Boolean(
        string="Custom Boolean",
    )

    @api.depends('is_paid', 'is_credit_time', 'number_of_hours', 'payslip_id', 'contract_id.wage',
                 'payslip_id.sum_worked_hours')
    def _compute_amount(self):
        super(HrPayslipWorkedDays, self)._compute_amount()
        for wd in self:
            if wd.custom_bool and wd.payslip_id.contract_id.add_standart!=0.0 and wd.payslip_id.wage_type == "hourly":
                rate = wd.contract_id.add_extra or 0.0
                wd.amount = wd.number_of_hours * rate


    @api.depends('work_entry_type_id', 'number_of_days', 'number_of_hours', 'payslip_id')
    def _compute_name(self):
        super(HrPayslipWorkedDays, self)._compute_name()
        for wd in self:
            if wd.custom_bool and wd.payslip_id.contract_id.add_standart!=0.0 and wd.payslip_id.wage_type != "monthly":
                wd.name = 'Paga mbi 200 ore'
            if wd.custom_bool == False and wd.code == 'WORK100':
                wd.name = 'Totali'    
            


